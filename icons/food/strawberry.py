from pixelkit import ellipse, poly


def draw(c):
    # 몸통: 아래 끝을 살짝 둥글게
    body = (ellipse(15.5, 14.5, 11.5, 8.5) | poly([(5, 16), (26, 16), (21, 23), (10, 23)])
            | ellipse(15.5, 23, 6, 4.5))
    c.fill(body, "red", shadow=2)
    c.fill({(9, 13), (9, 12), (10, 11), (11, 11)}, "red4")
    # 씨 (8개)
    for (x, y) in [(9, 16), (14, 15), (20, 15), (12, 20), (18, 20), (23, 13), (15, 24), (24, 17)]:
        c.px(x, y, "yellow3")
    # 꼭지 잎: 뾰족한 잎 5장이 부채꼴로
    leaves = [
        ([(15, 9), (3, 8), (11, 12)], "green2"),
        ([(16, 9), (28, 8), (20, 12)], "green1"),
        ([(13, 10), (6, 16), (15, 12)], "green2"),
        ([(18, 10), (25, 16), (16, 12)], "green1"),
        ([(14, 9), (15, 15), (17, 9)], "green2"),
    ]
    for pts, col in leaves:
        c.fill(poly(pts), col)
    # 잎 밝은 면 / 잎 사이 구분선
    c.fill({(5, 8), (6, 8), (7, 9), (8, 9), (8, 14), (9, 13)}, "green3")
    c.fill({(11, 12), (12, 12), (12, 13), (19, 12), (20, 12), (19, 13)}, "green0")
    c.fill({(15, 11), (15, 12), (15, 13)}, "green3")
    # 짧은 꼭지
    c.fill({(15, 5), (15, 6), (15, 7), (16, 3), (16, 4), (16, 5), (16, 6), (16, 7), (16, 8)}, "green1")
    c.fill({(15, 5), (15, 6), (15, 7), (15, 8)}, "green2")
