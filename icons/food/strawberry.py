from pixelkit import blob, poly


def draw(c):
    # 몸통: 어깨가 넓고 아래로 갈수록 좁아지는 원뿔형, 좌우 살짝 비대칭
    body = blob([
        (15.5, 9), (21, 7.5), (26.5, 10), (27.5, 15.5),
        (24.5, 22), (19.5, 27), (15, 28.5),
        (11, 26.5), (6.5, 21), (4.5, 15), (5.5, 10), (10.5, 7.5),
    ])
    c.fill(body, "red")
    # 씨
    for (x, y) in [(9, 15), (14, 14), (20, 14), (24, 15), (11, 20), (17, 19), (22, 20), (14, 24), (18, 25)]:
        if (x, y) in body:
            c.px(x, y, "yellow3")
    # 꼭지 잎: 뒤쪽 잎 -> 앞쪽 잎 순으로 그림자를 드리운다
    back_l = blob([(14, 9.5), (9, 8), (4.5, 9.5), (8, 12), (12.5, 12.5)])
    back_r = blob([(17, 9.5), (22, 7.5), (27, 9), (23.5, 12), (19, 12.5)])
    front_l = blob([(14.5, 10), (11, 12), (9.5, 15.5), (12.5, 14.5), (15, 12.5)])
    front_r = blob([(16.5, 10), (20, 12), (22, 15), (19, 14.5), (16.5, 13)])
    mid = blob([(14, 9.5), (14.5, 13), (15.5, 15), (16.5, 13), (17.5, 9.5)])
    for part in (back_l, back_r, front_l, front_r, mid):
        c.cast(part)
        c.fill(part, "green")
    # 꼭지
    c.fill({(15, 5), (15, 6), (15, 7), (16, 3), (16, 4), (16, 5), (16, 6), (16, 7)}, "green2")
    c.fill({(16, 5), (16, 6), (16, 7)}, "green1")
