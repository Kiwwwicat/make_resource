from pixelkit import blob


def draw(c):
    # 몸통: 조절점을 잇는 유기적 곡선. 어깨가 넓고 아래로 갈수록 좁아지며 좌우가 살짝 비대칭.
    body = blob([
        (15.5, 9),                    # 꼭지 홈 (살짝 들어감)
        (20, 7), (25, 9), (27.5, 15), # 오른쪽 어깨 -> 옆구리
        (26, 22), (21, 28),           # 오른쪽 아래
        (15.5, 27.5),                 # 바닥 홈
        (10, 28), (5, 22), (3.5, 15), # 왼쪽 아래 -> 옆구리
        (6, 9), (11, 7),              # 왼쪽 어깨
    ])
    c.fill(body, "red")               # 램프 이름만 -> 자동 입체 명암
    # 꼭지 홈의 그늘
    c.fill({(14, 9), (15, 10), (16, 10), (17, 9)}, "red1")
    # 꼭지
    c.fill({(15, 9), (15, 8), (15, 7), (16, 6), (16, 5), (17, 4)}, "brown2")
    c.fill({(16, 9), (16, 8), (16, 7)}, "brown1")
    # 잎
    c.grid(18, 3, [
        ".abb..",
        "abbbc.",
        ".bbccc",
        "..cc..",
    ], {"a": "green3", "b": "green2", "c": "green1"})
