from pixelkit import blob


def draw(c):
    # 줄기: 아래가 불룩하고 좌우가 살짝 다른 기둥
    stem = blob([
        (11.5, 15), (19.5, 15), (20.8, 19.5), (22.8, 24.2), (20, 27.2),
        (13, 27.5), (9.2, 25.6), (10.6, 20.5),
    ])
    # 갓: 위로 부풀고 아래는 평평한 편, 오른쪽이 약간 낮게 처진다
    cap = blob([
        (14.5, 4), (21, 5.2), (26.5, 9.8), (29, 15.5), (27.5, 19),
        (21, 20.2), (14, 20.5), (7, 19.8), (2.8, 18), (3, 13.5),
        (6, 9), (10, 6),
    ])
    c.cast(cap)
    c.fill(stem, "cream", round=4)
    c.cast(cap, depth=3)
    c.fill(cap, "red")
    # 갓 아래 그늘 한 줄
    c.recolor({(x, y) for (x, y) in cap if y >= 19}, "red1")
    # 흰 반점: 갓 위에만, 크기와 모양이 제각각
    spots = [
        blob([(8, 11), (11, 9.5), (12.5, 12), (10, 14), (7.5, 13.5)]),
        blob([(17, 7.5), (20.5, 7.8), (21, 10.5), (18, 11), (16.3, 9.8)]),
        blob([(22, 13), (25, 13), (25.5, 15.5), (22.5, 16.3)]),
        blob([(14, 14.5), (16.5, 14), (17, 16.5), (14.5, 17)]),
    ]
    for sp in spots:
        c.recolor(sp & cap, "cream3")
