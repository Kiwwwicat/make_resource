from pixelkit import blob


def draw(c):
    # 줄기: 아래가 불룩하고 좌우가 살짝 다른 기둥
    stem = blob([
        (11, 14), (19.8, 14), (20.8, 19.5), (23.2, 25), (20.5, 28.4),
        (13, 28.6), (8.8, 26.4), (10.4, 20.5),
    ])
    # 갓: 위로 부풀고 아래는 평평한 편, 오른쪽이 약간 낮게 처진다
    cap = blob([
        (13, 4), (19.5, 4.4), (25.8, 8.5), (29, 13.5), (27.6, 17.2),
        (21, 18.5), (14, 18.8), (7, 18.2), (2.8, 16.5), (3, 12.2),
        (6, 7.6), (9, 5),
    ])
    c.cast(cap)
    c.fill(stem, "cream", round=4)
    c.cast(cap, depth=3)
    c.fill(cap, "red")
    # 갓 아래 그늘 한 줄
    c.recolor({(x, y) for (x, y) in cap if y >= 17}, "red1")
    # 흰 반점: 갓 위에만, 크기와 모양이 제각각
    spots = [
        blob([(7.5, 10), (10.5, 8.6), (12, 11), (9.8, 13), (7, 12.5)]),
        blob([(17, 6.5), (20.5, 6.8), (21, 9.5), (18, 10), (16.3, 8.8)]),
        blob([(22.5, 11.8), (25.3, 12), (25.8, 14.5), (22.8, 15.2)]),
        blob([(14, 12.5), (16.5, 12), (17, 14.5), (14.5, 15)]),
    ]
    for sp in spots:
        c.recolor(sp & cap, "cream3")
