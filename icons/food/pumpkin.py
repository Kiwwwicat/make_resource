from pixelkit import ellipse


def draw(c):
    body = ellipse(8.5, 19, 6.5, 8.5) | ellipse(22.5, 19, 6.5, 8.5) | ellipse(15.5, 18.5, 8, 9.5)
    c.fill(body, "orange")
    # 세로 골: 가운데는 곧게, 옆은 몸통 곡선을 따라 휘게
    c.fill({(15, y) for y in range(12, 28)} | {(16, y) for y in range(12, 28)}, "orange1")
    left = [(10, 13), (9, 14), (9, 15), (9, 16), (9, 17), (9, 18), (9, 19), (9, 20), (9, 21), (10, 22),
            (10, 23), (10, 24), (11, 25), (11, 26)]
    right = [(21, 13), (22, 14), (22, 15), (22, 16), (22, 17), (22, 18), (22, 19), (22, 20), (22, 21),
             (21, 22), (21, 23), (21, 24), (20, 25), (20, 26)]
    c.fill(set(left) | set(right), "orange1")
    # 골 옆 밝은 면
    c.fill({(11, y) for y in range(15, 22)}, "orange3")
    c.fill({(17, y) for y in range(14, 22)}, "orange3")
    # 하이라이트
    c.fill({(5, 18), (5, 17), (6, 16), (7, 15), (12, 12), (13, 12)}, "orange4")
    # 꼭지
    c.fill({(14, 9), (15, 9), (16, 9), (17, 9), (14, 8), (15, 8), (16, 8), (15, 7), (16, 7),
            (16, 6), (17, 6), (17, 5)}, "brown2")
    c.fill({(17, 9), (17, 8), (17, 7), (18, 5), (18, 6)}, "brown1")
    c.fill({(14, 8), (15, 7), (16, 6), (17, 5)}, "brown3")
    # 덩굴손/잎
    c.grid(19, 8, [
        ".aab",
        "ab..",
        "b...",
    ], {"a": "green3", "b": "green2"})
