from pixelkit import blob, line


def draw(c):
    # 뒤쪽 좌우 덩어리 -> 앞 가운데 덩어리 순서로 겹쳐 세로 골을 만든다
    left = blob([(10, 10), (7, 12), (3.5, 17), (4, 23), (8, 27.5), (13, 27), (13.5, 18), (13, 11.5)])
    right = blob([(21, 10), (24, 11.5), (28, 16), (28, 22.5), (24, 27.5), (19, 27), (18, 18), (18.5, 11.5)])
    c.fill(left, "orange")
    c.cast(left)
    c.fill(right, "orange")
    mid = blob([(15, 9), (19.5, 9.5), (21.5, 15), (21, 22), (18.5, 28), (14, 28.5), (10.5, 25), (9.5, 17), (11, 11)])
    c.cast(mid)
    c.fill(mid, "orange")
    # 골 그늘: 가운데 덩어리 왼쪽 경계 / 오른쪽 경계를 따라 곡선
    c.recolor(line(10, 12, 9, 17) | line(9, 17, 10, 23) | line(10, 23, 13, 27), "orange1")
    c.recolor(line(20, 12, 22, 17) | line(22, 17, 21, 23) | line(21, 23, 19, 27), "orange1")
    # 꼭지: 가는 부품은 고정색 + 우하단 한 줄 어둡게
    stem = {(14, 9), (15, 9), (16, 9), (17, 9), (14, 8), (15, 8), (16, 8), (15, 7), (16, 7),
            (16, 6), (17, 6), (17, 5)}
    c.cast(stem)
    c.fill(stem, "brown2")
    c.fill({(17, 9), (17, 8), (17, 7), (18, 5), (18, 6), (16, 8)}, "brown1")
    c.fill({(14, 8), (15, 7), (16, 6), (17, 5)}, "brown3")
    c.grid(19, 8, [
        ".aab",
        "ab..",
        "b...",
    ], {"a": "green3", "b": "green2"})
